func extractFieldFromConstraint(constraint string) string {
	if field, ok := constraintFieldMap[constraint]; ok {
		return field
	}

	parts := strings.Split(constraint, "_")
	if len(parts) >= 2 {
		if parts[len(parts)-1] == "key" || parts[len(parts)-1] == "unique" {
			return parts[len(parts)-2]
		}
	}

	return "value"
}

func extractTableFromConstraint(constraint string) string {
	if table, ok := constraintTableMap[constraint]; ok {
		return table
	}
	parts := strings.Split(constraint, "_")
	if len(parts) > 0 {
		return cases.Title(language.English).String(strings.ReplaceAll(parts[0], "_", " "))
	}
	return "Record"
}

func extractResourceFromForeignKey(constraint string) string {
	if resource, ok := foreignKeyMap[constraint]; ok {
		return resource
	}
	// Auto-extract from "{table}_{resource}_id_fkey" — find the resource name
	// immediately before the "_id_fkey" suffix.
	if idx := strings.LastIndex(constraint, "_id_fkey"); idx > 0 {
		prefix := constraint[:idx]
		if last := strings.LastIndex(prefix, "_"); last >= 0 {
			return prefix[last+1:]
		}
		return prefix
	}
	return "referenced record"
}
func isConnectionError(err error) bool {
	if err == nil {
		return false
	}

	errStr := strings.ToLower(err.Error())
	connectionErrors := []string{
		"connection refused",
		"connection reset",
		"connection closed",
		"no connection",
		"broken pipe",
		"i/o timeout",
		"network is unreachable",
		"max clients reached", // Supabase pgbouncer: EMAXCONNSESSION
		"emaxconn",            // Supabase pgbouncer session-mode limit
	}

	for _, connErr := range connectionErrors {
		if strings.Contains(errStr, connErr) {
			return true
		}
	}

	return false
}

